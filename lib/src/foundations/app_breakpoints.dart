/// Standardized breakpoint values for responsive design
class AppBreakpoints {
  /// Mobile breakpoint threshold (< 768px)
  static const double mobile = 768.0;

  /// Tablet breakpoint threshold (>= 768px and < 1024px)
  static const double tablet = 1024.0;

  /// Desktop breakpoint threshold (>= 1024px)
  static const double desktop = 1200.0;

  /// Private constructor to prevent instantiation
  AppBreakpoints._();
}
